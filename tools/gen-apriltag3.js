// Generates js/dicts/<family>.js from the AprilTag 3 C sources (BSD-2-Clause,
// https://github.com/AprilRobotics/apriltag). Each file is loaded lazily by js/aruco.js.
// Usage: node tools/gen-apriltag3.js <dir-with-tag*.c> js/dicts
const fs = require('fs');
const path = require('path');

const [, , srcDir, outDir] = process.argv;
const FAMILIES = ['tagCircle21h7', 'tagCircle49h12', 'tagCustom48h12', 'tagStandard41h12', 'tagStandard52h13'];
fs.mkdirSync(outDir, { recursive: true });

for (const name of FAMILIES) {
  const src = fs.readFileSync(path.join(srcDir, name + '.c'), 'utf8');
  const num = (key) => Number(new RegExp(`tf->${key} = (-?\\d+);`).exec(src)[1]);
  const nbits = num('nbits');
  const ncodes = num('ncodes');
  const block = /codedata\[\d+\] = \{([\s\S]*?)\};/.exec(src)[1];
  const codes = [...block.matchAll(/0x([0-9a-fA-F]+)UL/g)].map((m) => BigInt('0x' + m[1]));
  if (codes.length !== ncodes) throw new Error(`${name}: code count ${codes.length} != ${ncodes}`);
  const bitX = [];
  const bitY = [];
  for (const m of src.matchAll(/tf->bit_x\[(\d+)\] = (-?\d+);/g)) bitX[Number(m[1])] = Number(m[2]);
  for (const m of src.matchAll(/tf->bit_y\[(\d+)\] = (-?\d+);/g)) bitY[Number(m[1])] = Number(m[2]);
  if (bitX.length !== nbits || bitY.length !== nbits) throw new Error(name + ': bit layout size');
  const bytesPerCode = Math.ceil(nbits / 8);
  const buf = Buffer.alloc(ncodes * bytesPerCode);
  codes.forEach((c, i) => {
    for (let b = 0; b < bytesPerCode; b++) {
      buf[i * bytesPerCode + b] = Number((c >> BigInt(8 * (bytesPerCode - 1 - b))) & 0xffn);
    }
  });
  const fam = {
    name,
    h: num('h'),
    nbits,
    count: ncodes,
    widthAtBorder: num('width_at_border'),
    totalWidth: num('total_width'),
    reversedBorder: /reversed_border = true/.test(src),
    bitX,
    bitY,
    bytesPerCode,
  };
  let out = `// AUTO-GENERATED by tools/gen-apriltag3.js from AprilTag 3 (${name}.c, BSD 2-Clause License,\n`;
  out += '// Copyright (C) 2013-2016, The Regents of The University of Michigan).\n';
  out += '// codes: big-endian, bytesPerCode bytes each, base64; bit i = (code >> (nbits-1-i)) & 1 at (bitX[i], bitY[i]).\n';
  out += `export default ${JSON.stringify(fam)};\n`;
  out += `export const CODES_BASE64 = ${JSON.stringify(buf.toString('base64'))};\n`;
  fs.writeFileSync(path.join(outDir, name + '.js'), out);
  console.log(name, ncodes, 'codes,', out.length, 'bytes');
}
