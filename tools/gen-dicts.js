// Generates js/aruco-dicts.js from OpenCV 4.10.0 source files
// (modules/objdetect/src/aruco/predefined_dictionaries.hpp and
//  apriltag/predefined_dictionaries_apriltag.hpp, Apache-2.0).
// Usage (inside a node container): node tools/gen-dicts.js <dir-with-hpp-files> js/aruco-dicts.js
const fs = require('fs');
const path = require('path');

const [, , srcDir, outFile] = process.argv;
const src =
  fs.readFileSync(path.join(srcDir, 'predefined_dictionaries.hpp'), 'utf8') +
  fs.readFileSync(path.join(srcDir, 'predefined_dictionaries_apriltag.hpp'), 'utf8');

function parseArray(name, markerSize) {
  const re = new RegExp(`static unsigned char ${name}\\[\\]\\[4\\]\\[(\\d+)\\]\\s*=`);
  const m = re.exec(src);
  if (!m) throw new Error('not found: ' + name);
  const nbytes = Number(m[1]);
  const end = src.indexOf('};', m.index);
  const nums = src.slice(m.index + m[0].length, end).match(/\d+/g).map(Number);
  const per = nbytes * 4;
  if (nums.length % per) throw new Error('bad length: ' + name);
  const nbits = markerSize * markerSize;
  const codes = [];
  for (let i = 0; i < nums.length; i += per) {
    // rotation 0 = first nbytes; MSB first; last byte holds remaining bits in its low bits
    let bits = '';
    for (let b = 0; b < nbytes; b++) {
      const remaining = nbits - b * 8;
      const take = Math.min(8, remaining);
      bits += nums[i + b].toString(2).padStart(8, '0').slice(8 - take);
    }
    if (bits.length !== nbits) throw new Error('bit count mismatch');
    codes.push(BigInt('0b' + bits).toString(16).padStart(Math.ceil(nbits / 4), '0'));
  }
  return codes;
}

// Source arrays: [name, markerSize]
const sources = {
  ARUCO: ['DICT_ARUCO_BYTES', 5],
  '4X4': ['DICT_4X4_1000_BYTES', 4],
  '5X5': ['DICT_5X5_1000_BYTES', 5],
  '6X6': ['DICT_6X6_1000_BYTES', 6],
  '7X7': ['DICT_7X7_1000_BYTES', 7],
  APRILTAG_16h5: ['DICT_APRILTAG_16h5_BYTES', 4],
  APRILTAG_25h9: ['DICT_APRILTAG_25h9_BYTES', 5],
  APRILTAG_36h10: ['DICT_APRILTAG_36h10_BYTES', 6],
  APRILTAG_36h11: ['DICT_APRILTAG_36h11_BYTES', 6],
  ARUCO_MIP_36h12: ['DICT_ARUCO_MIP_36h12_BYTES', 6],
};

const data = {};
for (const [key, [name, size]] of Object.entries(sources)) {
  data[key] = { markerSize: size, codes: parseArray(name, size) };
  console.log(key, data[key].codes.length);
}

let out = '// AUTO-GENERATED by tools/gen-dicts.js from OpenCV 4.10.0 (Apache License 2.0).\n';
out += '// Each code is the rotation-0 bit matrix (row-major, MSB first) as a hex string.\n';
out += 'export const DICT_SOURCES = {\n';
for (const [key, d] of Object.entries(data)) {
  out += `  ${JSON.stringify(key)}: { markerSize: ${d.markerSize}, codes: ${JSON.stringify(d.codes.join(' '))} },\n`;
}
out += '};\n';
fs.writeFileSync(outFile, out);
console.log('written', outFile, out.length, 'bytes');
